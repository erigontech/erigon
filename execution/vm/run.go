// run is Run's loop. Its tracing code sits behind runTracing, so this copy
// compiles without it; runTraced in run_traced_gen.go is the same source with
// runTracing set to true.
func (evm *EVM) run(contract Contract, gas mdgas.MdGas, input []byte, readOnly, debug, trace bool) (ret []byte, gasRemaining mdgas.MdGas, gasUsed mdgas.MdGasUsage, err error) {
	// Don't bother with the execution if there's no code.
	if len(contract.Code) == 0 {
		return nil, gas, mdgas.MdGasUsage{}, nil
	}

	// Reset the previous call's return data. It's unimportant to preserve the old buffer
	// as every returning call will return new data anyway.
	evm.returnData = nil

	var (
		op          OpCode // current opcode
		callContext = getCallContext(contract, input, gas)
		// For optimisation reason we're using uint64 as the program counter.
		// It's theoretically possible to go above 2^64. The YP defines the PC
		// to be uint256. Practically much less so feasible.
		pc   = uint64(0) // program counter
		cost mdgas.MdGasCost
		// copies used by tracer
		pcCopy  uint64 // needed for the deferred Tracer
		oldGas  mdgas.MdGas
		callGas mdgas.MdGasCost
		logged  bool   // deferred Tracer should ignore already logged steps
		res     []byte // result of the opcode execution function
		tracer  = evm.config.Tracer
	)

	// Make sure the readOnly is only set if we aren't in readOnly yet.
	// This makes also sure that the readOnly flag isn't removed for child calls.
	restoreReadonly := readOnly && !evm.readOnly
	if restoreReadonly {
		evm.readOnly = true
	}
	// Increment the call depth which is restricted to 1024
	evm.depth++
	defer func() {
		// EIP-8037: snapshot the spilled portion and derive the frame's net
		// state-gas usage from the reservoir delta before callContext.put()
		// clears them. A state charge lowers stateGas (or raises stateGasSpill
		// on spill) and a refill reverses it, so the net used (signed) is
		// (initialReservoir - stateGas) + stateGasSpill. gasUsed.Execution is
		// derived uniformly by evm.call/evm.create's defer from the final
		// gasRemaining (covers precompile/no-code paths and the revert burn).
		gasUsed.StateSpill = callContext.stateGasSpill
		gasUsed.State = int64(gas.State) - int64(callContext.stateGas) + int64(callContext.stateGasSpill)
		callContext.put()
		if restoreReadonly {
			evm.readOnly = false
		}
		evm.depth--
	}()

	// Registered after the cleanup defer so LIFO runs it first: the tracer needs
	// the stacks before callContext.put() returns them to the pool.
	if runTracing && debug {
		defer func() {
			if err == nil {
				return
			}
			switch {
			case !logged && tracer.HasOpcodeHook() && tracer.WantsOpcode(byte(op)):
				tracer.EmitOpcode(pcCopy, byte(op), oldGas, cost, callContext, evm.returnData, evm.depth, VMErrorFromErr(err))
			case tracer.HasOpcodeHook() && tracer.HasFaultHook():
				tracer.EmitFault(pcCopy, byte(op), oldGas, cost, callContext, evm.depth, VMErrorFromErr(err))
			}
		}()
	}

	// The Interpreter main run loop (contextual). This loop runs until either an
	// explicit STOP, RETURN or SELFDESTRUCT is executed, an error occurred during
	// the execution of one of the operations or until the done flag is set by the
	// parent context.

	// Hoist to locals so the compiler sees them as loop-invariant.
	stack := &callContext.Stack
	jt := evm.jt

run:
	for {
		op = contract.GetOp(pc)
		// The hottest constant-gas opcodes skip the jump table and its indirect
		// call. A failed stack or gas check falls through to the generic path,
		// which reports the error. TestFastPathMatchesJumpTables pins the constants.
		if !runTracing {
			sLen, gas := stack.len(), callContext.gas
			switch op {
			// Cases below are generated by execution/vm/gen from its fastOps table; do not edit them.
			case PUSH1:
				if sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					pc, _, _ = opPush1(pc, evm, callContext)
					pc++
					continue
				}
			case PUSH2:
				if sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					pc, _, _ = opPush2(pc, evm, callContext)
					pc++
					continue
				}
			case ADD:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					x, y := stack.pop1Peek1()
					y.Add(x, y)
					pc++
					continue
				}
			case POP:
				if sLen >= 1 && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					stack.drop()
					pc++
					continue
				}
			case JUMPDEST:
				if gas >= params.JumpdestGas {
					callContext.gas = gas - params.JumpdestGas
					pc++
					continue
				}
			case JUMP:
				if sLen >= 1 && gas >= GasMidStep {
					callContext.gas = gas - GasMidStep
					if pc, res, err = opJump(pc, evm, callContext); err != nil {
						break run
					}
					pc++
					continue
				}
			case JUMPI:
				if sLen >= 2 && gas >= GasSlowStep {
					callContext.gas = gas - GasSlowStep
					if pc, res, err = opJumpi(pc, evm, callContext); err != nil {
						break run
					}
					pc++
					continue
				}
			case SUB:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opSub(pc, evm, callContext)
					pc++
					continue
				}
			case MUL:
				if sLen >= 2 && gas >= GasFastStep {
					callContext.gas = gas - GasFastStep
					_, _, _ = opMul(pc, evm, callContext)
					pc++
					continue
				}
			case DIV:
				if sLen >= 2 && gas >= GasFastStep {
					callContext.gas = gas - GasFastStep
					_, _, _ = opDiv(pc, evm, callContext)
					pc++
					continue
				}
			case LT:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opLt(pc, evm, callContext)
					pc++
					continue
				}
			case GT:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opGt(pc, evm, callContext)
					pc++
					continue
				}
			case EQ:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opEq(pc, evm, callContext)
					pc++
					continue
				}
			case AND:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opAnd(pc, evm, callContext)
					pc++
					continue
				}
			case ISZERO:
				if sLen >= 1 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opIszero(pc, evm, callContext)
					pc++
					continue
				}
			case SDIV:
				if sLen >= 2 && gas >= GasFastStep {
					callContext.gas = gas - GasFastStep
					_, _, _ = opSdiv(pc, evm, callContext)
					pc++
					continue
				}
			case MOD:
				if sLen >= 2 && gas >= GasFastStep {
					callContext.gas = gas - GasFastStep
					_, _, _ = opMod(pc, evm, callContext)
					pc++
					continue
				}
			case SMOD:
				if sLen >= 2 && gas >= GasFastStep {
					callContext.gas = gas - GasFastStep
					_, _, _ = opSmod(pc, evm, callContext)
					pc++
					continue
				}
			case ADDMOD:
				if sLen >= 3 && gas >= GasMidStep {
					callContext.gas = gas - GasMidStep
					_, _, _ = opAddmod(pc, evm, callContext)
					pc++
					continue
				}
			case MULMOD:
				if sLen >= 3 && gas >= GasMidStep {
					callContext.gas = gas - GasMidStep
					_, _, _ = opMulmod(pc, evm, callContext)
					pc++
					continue
				}
			case SIGNEXTEND:
				if sLen >= 2 && gas >= GasFastStep {
					callContext.gas = gas - GasFastStep
					_, _, _ = opSignExtend(pc, evm, callContext)
					pc++
					continue
				}
			case SLT:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opSlt(pc, evm, callContext)
					pc++
					continue
				}
			case SGT:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opSgt(pc, evm, callContext)
					pc++
					continue
				}
			case OR:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opOr(pc, evm, callContext)
					pc++
					continue
				}
			case XOR:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opXor(pc, evm, callContext)
					pc++
					continue
				}
			case NOT:
				if sLen >= 1 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opNot(pc, evm, callContext)
					pc++
					continue
				}
			case BYTE:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opByte(pc, evm, callContext)
					pc++
					continue
				}
			case CALLDATALOAD:
				if sLen >= 1 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					_, _, _ = opCallDataLoad(pc, evm, callContext)
					pc++
					continue
				}
			case ADDRESS:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opAddress(pc, evm, callContext)
					pc++
					continue
				}
			case ORIGIN:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opOrigin(pc, evm, callContext)
					pc++
					continue
				}
			case CALLER:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opCaller(pc, evm, callContext)
					pc++
					continue
				}
			case CALLVALUE:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opCallValue(pc, evm, callContext)
					pc++
					continue
				}
			case CALLDATASIZE:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opCallDataSize(pc, evm, callContext)
					pc++
					continue
				}
			case CODESIZE:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opCodeSize(pc, evm, callContext)
					pc++
					continue
				}
			case GASPRICE:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opGasprice(pc, evm, callContext)
					pc++
					continue
				}
			case COINBASE:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opCoinbase(pc, evm, callContext)
					pc++
					continue
				}
			case TIMESTAMP:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opTimestamp(pc, evm, callContext)
					pc++
					continue
				}
			case NUMBER:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opNumber(pc, evm, callContext)
					pc++
					continue
				}
			case GASLIMIT:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opGasLimit(pc, evm, callContext)
					pc++
					continue
				}
			case PC:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opPc(pc, evm, callContext)
					pc++
					continue
				}
			case MSIZE:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opMsize(pc, evm, callContext)
					pc++
					continue
				}
			case GAS:
				if sLen < stackLimit && gas >= GasQuickStep {
					callContext.gas = gas - GasQuickStep
					_, _, _ = opGas(pc, evm, callContext)
					pc++
					continue
				}
			case DUP1:
				if sLen >= 1 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(0)
					pc++
					continue
				}
			case DUP2:
				if sLen >= 2 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(1)
					pc++
					continue
				}
			case DUP3:
				if sLen >= 3 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(2)
					pc++
					continue
				}
			case DUP4:
				if sLen >= 4 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(3)
					pc++
					continue
				}
			case DUP5:
				if sLen >= 5 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(4)
					pc++
					continue
				}
			case DUP6:
				if sLen >= 6 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(5)
					pc++
					continue
				}
			case DUP7:
				if sLen >= 7 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(6)
					pc++
					continue
				}
			case DUP8:
				if sLen >= 8 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(7)
					pc++
					continue
				}
			case DUP9:
				if sLen >= 9 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(8)
					pc++
					continue
				}
			case DUP10:
				if sLen >= 10 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(9)
					pc++
					continue
				}
			case DUP11:
				if sLen >= 11 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(10)
					pc++
					continue
				}
			case DUP12:
				if sLen >= 12 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(11)
					pc++
					continue
				}
			case DUP13:
				if sLen >= 13 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(12)
					pc++
					continue
				}
			case DUP14:
				if sLen >= 14 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(13)
					pc++
					continue
				}
			case DUP15:
				if sLen >= 15 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(14)
					pc++
					continue
				}
			case DUP16:
				if sLen >= 16 && sLen < stackLimit && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.dup(15)
					pc++
					continue
				}
			case SWAP1:
				if sLen >= 2 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(1)
					pc++
					continue
				}
			case SWAP2:
				if sLen >= 3 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(2)
					pc++
					continue
				}
			case SWAP3:
				if sLen >= 4 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(3)
					pc++
					continue
				}
			case SWAP4:
				if sLen >= 5 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(4)
					pc++
					continue
				}
			case SWAP5:
				if sLen >= 6 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(5)
					pc++
					continue
				}
			case SWAP6:
				if sLen >= 7 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(6)
					pc++
					continue
				}
			case SWAP7:
				if sLen >= 8 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(7)
					pc++
					continue
				}
			case SWAP8:
				if sLen >= 9 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(8)
					pc++
					continue
				}
			case SWAP9:
				if sLen >= 10 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(9)
					pc++
					continue
				}
			case SWAP10:
				if sLen >= 11 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(10)
					pc++
					continue
				}
			case SWAP11:
				if sLen >= 12 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(11)
					pc++
					continue
				}
			case SWAP12:
				if sLen >= 13 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(12)
					pc++
					continue
				}
			case SWAP13:
				if sLen >= 14 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(13)
					pc++
					continue
				}
			case SWAP14:
				if sLen >= 15 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(14)
					pc++
					continue
				}
			case SWAP15:
				if sLen >= 16 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(15)
					pc++
					continue
				}
			case SWAP16:
				if sLen >= 17 && gas >= GasFastestStep {
					callContext.gas = gas - GasFastestStep
					stack.swap(16)
					pc++
					continue
				}
				// End of generated cases.
			}
		}
		callContext.cacheGen++
		if runTracing && debug {
			// Capture pre-execution values for tracing.
			logged = false
			pcCopy = pc
			oldGas = callContext.Gas()
		}
		// Get the operation from the jump table and validate the stack to ensure there are
		// enough stack items available to perform the operation.
		operation := &jt[op]
		cost = mdgas.MdGasCost{Execution: operation.constantGas} // For tracing
		// Valid iff numPop <= sLen <= maxStack, as one unsigned range check:
		// a stack shallower than numPop wraps negative and fails the compare.
		if sLen := stack.len(); uint(sLen-operation.numPop) > uint(operation.maxStack-operation.numPop) {
			return nil, callContext.Gas(), mdgas.MdGasUsage{}, stackBoundsErr(sLen, operation)
		}
		// for tracing: this gas consumption event is emitted below in the debug section.
		if callContext.gas < cost.Execution {
			return nil, callContext.Gas(), mdgas.MdGasUsage{}, ErrOutOfGas
		} else {
			callContext.gas -= cost.Execution
		}

		// All ops with a dynamic memory usage also has a dynamic gas cost.
		var memorySize uint64
		if operation.dynamicGas != nil {
			// calculate the new memory size and expand the memory to fit
			// the operation
			// Memory check needs to be done prior to evaluating the dynamic gas portion,
			// to detect calculation overflows
			if operation.memorySize != nil {
				memSize, overflow := operation.memorySize(callContext)
				if overflow {
					return nil, callContext.Gas(), mdgas.MdGasUsage{}, ErrGasUintOverflow
				}
				// memory is expanded in words of 32 bytes. Gas
				// is also calculated in words.
				if memorySize, overflow = math.SafeMul(ToWordSize(memSize), 32); overflow {
					return nil, callContext.Gas(), mdgas.MdGasUsage{}, ErrGasUintOverflow
				}
			}
			// Reset callGasTemp so we can detect if dynamicGas sets it (CALL variants)
			evm.callGasTemp = 0
			// Consume the gas and return an error if not enough gas is available.
			// cost is explicitly set so that the capture state defer method can get the proper cost
			var dynamicCost mdgas.MdGasCost
			dynamicCost, err = operation.dynamicGas(evm, callContext, callContext.Gas(), memorySize)
			if err != nil {
				if !errors.Is(err, ErrOutOfGas) {
					err = fmt.Errorf("%w: %w", ErrOutOfGas, err)
				}
				return nil, callContext.Gas(), mdgas.MdGasUsage{}, err
			}
			if runTracing {
				cost = cost.Plus(dynamicCost)
				callGas = cost
				callGas.Execution -= evm.CallGasTemp()
				if dbg.TraceDynamicGas && dynamicCost != (mdgas.MdGasCost{}) {
					gasCost := traceGas(op, callGas, cost)
					fmt.Printf("%d (%d.%d) Dynamic Gas: %d %d (%s)\n", evm.intraBlockState.BlockNumber(), evm.intraBlockState.TxIndex(), evm.intraBlockState.Incarnation(), gasCost.Execution, gasCost.State, op)
				}
			}
			if callContext.gas < dynamicCost.Execution {
				return nil, callContext.Gas(), mdgas.MdGasUsage{}, ErrOutOfGas
			}
			callContext.gas -= dynamicCost.Execution
			if dynamicCost.State > 0 {
				ok := callContext.useMdGas(uint64(dynamicCost.State), mdgas.StateGas, nil, tracing.GasChangeIgnored)
				if !ok {
					return nil, callContext.Gas(), mdgas.MdGasUsage{}, ErrOutOfGas
				}
			} else if dynamicCost.State < 0 {
				callContext.refillStateGas(uint64(-dynamicCost.State), nil, tracing.GasChangeIgnored)
			}
		}

		// Do gas tracing before memory expansion
		if runTracing && debug {
			if tracer.HasGasChangeHook() {
				tracer.EmitGasChange(oldGas, callContext.Gas(), tracing.GasChangeCallOpCode)
			}
			if tracer.HasOpcodeHook() && tracer.WantsOpcode(byte(op)) {
				tracer.EmitOpcode(pc, byte(op), oldGas, cost, callContext, evm.returnData, evm.depth, VMErrorFromErr(err))
				logged = true
			}
		}

		if memorySize > 0 {
			callContext.Memory.Resize(memorySize)
		}

		// TODO - move this to a trace & set in the worker

		if runTracing && trace {
			var opstr string
			if operation.string != nil {
				opstr = operation.string(pc, callContext)
			} else {
				opstr = op.String()
			}

			gasCost := traceGas(op, callGas, cost)
			fmt.Printf("%d (%d.%d) %5d %5d %5d %s\n", evm.intraBlockState.BlockNumber(), evm.intraBlockState.TxIndex(), evm.intraBlockState.Incarnation(), pc, gasCost.Execution, gasCost.State, opstr)
		}

		// execute the operation
		pc, res, err = operation.execute(pc, evm, callContext)
		if err != nil {
			break
		}
		pc++
	}

	if errors.Is(err, errStopToken) {
		err = nil // clear stop token error
	}

	return res, callContext.Gas(), mdgas.MdGasUsage{}, err
}
