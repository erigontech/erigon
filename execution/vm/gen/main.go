// gen writes the interpreter's generated code from run.go and the fastOps table:
// the fast-path cases inside run.go, run_traced_gen.go (func run renamed to
// runTraced, with runTracing set to true) and fast_path_gen_test.go.
// With -check it reports stale files instead of writing them.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"slices"
	"strings"
)

// fastOp is one opcode the untraced loop runs without the jump table. Every
// entry must charge only constant gas, must not fail once its stack and gas
// checks pass, and must not use the CallContext intern cache: the fast path
// skips cacheGen++. TestFastPathMatchesJumpTables pins it against all forks.
type fastOp struct {
	name      string
	execute   string // jump-table execute func; "" for the makeDup closures
	gas       string
	pop, push int
	body      string
}

func fastOps() []fastOp {
	call := func(name, fn, gas string, pop int) fastOp {
		return fastOp{name, fn, gas, pop, 1, "_, _, _ = " + fn + "(pc, evm, callContext)"}
	}
	jump := func(name, fn, gas string, pop int) fastOp {
		return fastOp{name, fn, gas, pop, 0, "if pc, res, err = " + fn + "(pc, evm, callContext); err != nil {\nbreak run\n}"}
	}
	ops := []fastOp{
		{"PUSH1", "opPush1", "GasFastestStep", 0, 1, "pc, _, _ = opPush1(pc, evm, callContext)"},
		{"PUSH2", "opPush2", "GasFastestStep", 0, 1, "pc, _, _ = opPush2(pc, evm, callContext)"},
		{"ADD", "opAdd", "GasFastestStep", 2, 1, "x, y := stack.pop1Peek1()\ny.Add(x, y)"},
		{"POP", "opPop", "GasQuickStep", 1, 0, "stack.drop()"},
		{"JUMPDEST", "opJumpdest", "params.JumpdestGas", 0, 0, ""},
		jump("JUMP", "opJump", "GasMidStep", 1),
		jump("JUMPI", "opJumpi", "GasSlowStep", 2),
		call("SUB", "opSub", "GasFastestStep", 2),
		call("MUL", "opMul", "GasFastStep", 2),
		call("DIV", "opDiv", "GasFastStep", 2),
		call("LT", "opLt", "GasFastestStep", 2),
		call("GT", "opGt", "GasFastestStep", 2),
		call("EQ", "opEq", "GasFastestStep", 2),
		call("AND", "opAnd", "GasFastestStep", 2),
		call("ISZERO", "opIszero", "GasFastestStep", 1),
		call("SDIV", "opSdiv", "GasFastStep", 2),
		call("MOD", "opMod", "GasFastStep", 2),
		call("SMOD", "opSmod", "GasFastStep", 2),
		call("ADDMOD", "opAddmod", "GasMidStep", 3),
		call("MULMOD", "opMulmod", "GasMidStep", 3),
		call("SIGNEXTEND", "opSignExtend", "GasFastStep", 2),
		call("SLT", "opSlt", "GasFastestStep", 2),
		call("SGT", "opSgt", "GasFastestStep", 2),
		call("OR", "opOr", "GasFastestStep", 2),
		call("XOR", "opXor", "GasFastestStep", 2),
		call("NOT", "opNot", "GasFastestStep", 1),
		call("BYTE", "opByte", "GasFastestStep", 2),
		call("CALLDATALOAD", "opCallDataLoad", "GasFastestStep", 1),
		call("ADDRESS", "opAddress", "GasQuickStep", 0),
		call("ORIGIN", "opOrigin", "GasQuickStep", 0),
		call("CALLER", "opCaller", "GasQuickStep", 0),
		call("CALLVALUE", "opCallValue", "GasQuickStep", 0),
		call("CALLDATASIZE", "opCallDataSize", "GasQuickStep", 0),
		call("CODESIZE", "opCodeSize", "GasQuickStep", 0),
		call("GASPRICE", "opGasprice", "GasQuickStep", 0),
		call("COINBASE", "opCoinbase", "GasQuickStep", 0),
		call("TIMESTAMP", "opTimestamp", "GasQuickStep", 0),
		call("NUMBER", "opNumber", "GasQuickStep", 0),
		call("GASLIMIT", "opGasLimit", "GasQuickStep", 0),
		call("PC", "opPc", "GasQuickStep", 0),
		call("MSIZE", "opMsize", "GasQuickStep", 0),
		call("GAS", "opGas", "GasQuickStep", 0),
	}
	for n := 1; n <= 16; n++ {
		ops = append(ops, fastOp{fmt.Sprintf("DUP%d", n), "", "GasFastestStep", n, n + 1, fmt.Sprintf("stack.dup(%d)", n-1)})
	}
	for n := 1; n <= 16; n++ {
		ops = append(ops, fastOp{fmt.Sprintf("SWAP%d", n), fmt.Sprintf("opSwap%d", n), "GasFastestStep", n + 1, n + 1, fmt.Sprintf("stack.swap(%d)", n)})
	}
	return ops
}

const (
	beginCases = "// Cases below are generated by execution/vm/gen from its fastOps table; do not edit them.\n"
	endCases   = "// End of generated cases.\n"
)

func fastCases(ops []fastOp) string {
	var b strings.Builder
	for _, o := range ops {
		var cond []string
		if o.pop > 0 {
			cond = append(cond, fmt.Sprintf("sLen >= %d", o.pop))
		}
		switch o.push - o.pop {
		case 1:
			cond = append(cond, "sLen < stackLimit")
		case 0, -1, -2:
		default:
			log.Fatalf("%s: stack growth %d needs its own bound", o.name, o.push-o.pop)
		}
		cond = append(cond, "gas >= "+o.gas)
		fmt.Fprintf(&b, "case %s:\nif %s {\ncallContext.gas = gas - %s\n", o.name, strings.Join(cond, " && "), o.gas)
		if o.body != "" {
			b.WriteString(o.body + "\n")
		}
		b.WriteString("pc++\ncontinue\n}\n")
	}
	return b.String()
}

func withFastCases(src []byte, ops []fastOp) []byte {
	s := string(src)
	i := strings.Index(s, beginCases)
	j := strings.Index(s, endCases)
	if i < 0 || j < i {
		log.Fatal("run.go: generated-cases markers not found")
	}
	out, err := format.Source([]byte(s[:i+len(beginCases)] + fastCases(ops) + s[j:]))
	if err != nil {
		log.Fatal(err)
	}
	return out
}

func tracedCopy(run []byte) []byte {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "run.go", run, parser.SkipObjectResolution)
	if err != nil {
		log.Fatal(err)
	}
	f.Decls = slices.DeleteFunc(f.Decls, func(d ast.Decl) bool {
		if fn, ok := d.(*ast.FuncDecl); ok {
			return fn.Name.Name != "run"
		}
		return d.(*ast.GenDecl).Tok != token.IMPORT
	})
	for n := range ast.Preorder(f) {
		switch n := n.(type) {
		case *ast.FuncDecl:
			n.Name.Name = "runTraced"
		case *ast.Ident:
			if n.Name == "runTracing" {
				n.Name = "true"
			}
		}
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by execution/vm/gen from run.go. DO NOT EDIT.\n\n")
	if err := format.Node(&buf, fset, f); err != nil {
		log.Fatal(err)
	}
	return buf.Bytes()
}

func testTable(ops []fastOp) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by execution/vm/gen. DO NOT EDIT.\n\npackage vm\n\n")
	b.WriteString("import \"github.com/erigontech/erigon/execution/protocol/params\"\n\n")
	b.WriteString("var fastPathOps = map[OpCode]fastPathWant{\n")
	for _, o := range ops {
		execute := o.execute
		if execute == "" {
			execute = "nil"
		}
		fmt.Fprintf(&b, "%s: {%s, %s, %d, %d},\n", o.name, execute, o.gas, o.pop, o.push)
	}
	b.WriteString("}\n")
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	return out
}

func main() {
	check := len(os.Args) > 1 && os.Args[1] == "-check"
	src, err := os.ReadFile("run.go")
	if err != nil {
		log.Fatal(err)
	}
	ops := fastOps()
	run := withFastCases(src, ops)
	files := []struct {
		name string
		data []byte
	}{
		{"run.go", run},
		{"run_traced_gen.go", tracedCopy(run)},
		{"fast_path_gen_test.go", testTable(ops)},
	}
	var stale []string
	for _, f := range files {
		if !check {
			if err := os.WriteFile(f.name, f.data, 0o644); err != nil {
				log.Fatal(err)
			}
			continue
		}
		// Compare after formatting with this toolchain: gofmt output varies across Go versions.
		got, err := os.ReadFile(f.name)
		if err == nil {
			got, err = format.Source(got)
		}
		if err != nil || !bytes.Equal(got, f.data) {
			stale = append(stale, f.name)
		}
	}
	if len(stale) > 0 {
		log.Fatalf("stale %v: run go generate ./execution/vm", stale)
	}
}
