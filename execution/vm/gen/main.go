// gen writes run_traced_gen.go: func run from run.go, renamed to runTraced,
// with runTracing set to true. With -stdout it prints the file instead.
package main

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"slices"
)

func main() {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "run.go", nil, parser.SkipObjectResolution)
	if err != nil {
		log.Fatal(err)
	}
	f.Decls = slices.DeleteFunc(f.Decls, func(d ast.Decl) bool {
		if fn, ok := d.(*ast.FuncDecl); ok {
			return fn.Name.Name != "run"
		}
		return d.(*ast.GenDecl).Tok != token.IMPORT
	})
	for n := range ast.Preorder(f) {
		switch n := n.(type) {
		case *ast.FuncDecl:
			n.Name.Name = "runTraced"
		case *ast.Ident:
			if n.Name == "runTracing" {
				n.Name = "true"
			}
		}
	}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by execution/vm/gen from run.go. DO NOT EDIT.\n\n")
	if err := format.Node(&buf, fset, f); err != nil {
		log.Fatal(err)
	}
	if len(os.Args) > 1 && os.Args[1] == "-stdout" {
		os.Stdout.Write(buf.Bytes())
		return
	}
	if err := os.WriteFile("run_traced_gen.go", buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
