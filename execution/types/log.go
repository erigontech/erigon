// BuildTopicMap converts a slice-of-alternatives representation of topics into a
// pre-built lookup map suitable for repeated calls to FilterWithTopicMap.
func BuildTopicMap(topics [][]common.Hash) []map[common.Hash]struct{} {
	topicMap := make([]map[common.Hash]struct{}, len(topics))
	for idx, v := range topics {
		if len(v) == 0 {
			continue // nil entry = wildcard; FilterWithTopicMap treats len(nil)==0 as match-all
		}
		topicMap[idx] = make(map[common.Hash]struct{}, len(v))
		for _, h := range v {
			topicMap[idx][h] = struct{}{}
		}
	}
	return topicMap
}

// FilterWithTopicMap filters logs using a pre-built topic map. Use this when filtering
// in a loop with the same topics to avoid rebuilding the map on every call.
func (logs Logs) FilterWithTopicMap(addrMap map[common.Address]struct{}, topicMap []map[common.Hash]struct{}, maxLogs uint64) Logs {
	o := make(Logs, 0, len(logs))
	var logCount uint64
	for _, v := range logs {
		if len(addrMap) != 0 {
			if _, ok := addrMap[v.Address]; !ok {
				continue
			}
		}
		if len(topicMap) > len(v.Topics) {
			continue
		}
		found := true
		for idx, topicSet := range topicMap {
			if len(topicSet) == 0 {
				continue
			}
			if _, ok := topicSet[v.Topics[idx]]; !ok {
				found = false
				break
			}
		}
		if found {
			o = append(o, v)
		}
		logCount++
		if maxLogs != 0 && logCount >= maxLogs {
			break
		}
	}
	return o
}

func (logs Logs) Filter(addrMap map[common.Address]struct{}, topics [][]common.Hash, maxLogs uint64) Logs {
	return logs.FilterWithTopicMap(addrMap, BuildTopicMap(topics), maxLogs)
}

func (logs Logs) ContainingTopics(addrMap map[common.Address]struct{}, topicsMap map[common.Hash]struct{}, maxLogs uint64) Logs {
	o := make(Logs, 0, len(logs))
	var logCount uint64

	for _, v := range logs {
		found := false

		// check address if addrMap is not empty
		if _, requested := addrMap[v.Address]; !requested && len(addrMap) > 0 {
			continue // not there? skip this log
		}
		//topicsMap len zero match any topics
		if len(topicsMap) == 0 {
			o = append(o, v)
		} else {
			for i := range v.Topics {
				//Contain any topics that matched
				if _, ok := topicsMap[v.Topics[i]]; ok {
					found = true
				}
			}
			if found {
				o = append(o, v)
			}
		}
		logCount += 1
		if maxLogs != 0 && logCount >= maxLogs {
			break
		}
	}
	return o
}

type rlpLog struct {
	Address common.Address
	Topics  []common.Hash
	Data    []byte
}

type rlpStorageLog struct {
	Address common.Address
	Topics  []common.Hash
	Data    []byte
	//BlockNumber uint64
	//TxHash common.Hash
	//TxIndex uint
	//BlockHash   common.Hash
	//Index uint
}

// EncodeRLP implements rlp.Encoder.
func (l *Log) EncodeRLP(w io.Writer) error {
	return rlp.Encode(w, &rlpLog{Address: l.Address, Topics: l.Topics, Data: l.Data})
}

func (l *Log) payloadSize() int {
	topicsLen := (1 + length.Hash) * len(l.Topics)
	return rlp.StringLen(l.Address[:]) + rlp.ListPrefixLen(topicsLen) + topicsLen + rlp.StringLen(l.Data)
}

func (l *Log) encodingSize() int {
	return rlp.ListLen(l.payloadSize())
}

func (l *Log) encodeRLP(w io.Writer, b []byte) error {
	if err := rlp.EncodeListPrefix(l.payloadSize(), w, b); err != nil {
		return err
	}
	if err := rlp.EncodeString(l.Address[:], w, b); err != nil {
		return err
	}
	if err := rlp.EncodeListPrefix((1+length.Hash)*len(l.Topics), w, b); err != nil {
		return err
	}
	for i := range l.Topics {
		if err := rlp.EncodeString(l.Topics[i][:], w, b); err != nil {
			return err
		}
	}
	return rlp.EncodeString(l.Data, w, b)
}

// DecodeRLP implements rlp.Decoder.
func (l *Log) DecodeRLP(s *rlp.Stream) error {
	var dec rlpLog
	err := s.Decode(&dec)
	if err == nil {
		l.Address, l.Topics, l.Data = dec.Address, dec.Topics, dec.Data
	}
	return err
}

// RlpHashLogs hashes the concatenation of the given log groups as one RLP list,
// without flattening them into a single slice first.
func RlpHashLogs(groups []Logs) common.Hash {
	return rlpPayloadHash(func(w io.Writer, b []byte) error {
		payloadSize := 0
		for _, logs := range groups {
			for _, l := range logs {
				payloadSize += l.encodingSize()
			}
		}
		if err := rlp.EncodeListPrefix(payloadSize, w, b); err != nil {
			return err
		}
		for _, logs := range groups {
			for _, l := range logs {
				if err := l.encodeRLP(w, b); err != nil {
					return err
				}
			}
		}
		return nil
	})
}

// Copy creates a deep copy of the Log.
func (l *Log) Copy() *Log {
	if l == nil {
		return nil
	}
	dst := &Log{
		Topics: make([]common.Hash, len(l.Topics)),
		Data:   make(hexutil.Bytes, len(l.Data)),
	}
	l.CopyTo(dst)
	return dst
}

// CopyTo
func (l *Log) CopyTo(dst *Log) {
	t, d := dst.Topics, dst.Data
	*dst = *l
	dst.Topics = t[:copy(t, l.Topics)]
	dst.Data = d[:copy(d, l.Data)]
}

// LogForStorage is a wrapper around a Log that flattens and parses the entire content of
// a log including non-consensus fields.
type LogForStorage Log

// EncodeRLP implements rlp.Encoder.
func (l *LogForStorage) EncodeRLP(w io.Writer) error {
	return rlp.Encode(w, &rlpStorageLog{
		Address: l.Address,
		Topics:  l.Topics,
		Data:    l.Data,
	})
}

func decodeHashList(s *rlp.Stream) (list []common.Hash, err error) {
	l, err := s.List()
	if err != nil {
		return nil, err
	}
	if l == 0 {
		return []common.Hash{}, s.ListEnd()
	}
	listLen := l / (1 + 32)            // rlpLenPrefix+32bytes
	preAlloc := int(min(128, listLen)) // attacker may craft rlp prefix - which will trigger huge pre-alloc. so, add hard-limit
	list = make([]common.Hash, 0, preAlloc)
	for s.MoreDataInList() {
		h, err := s.ReadHash()
		if err != nil {
			return nil, err
		}
		list = append(list, h)
	}
	return list, s.ListEnd()
}

// DecodeRLP implements rlp.Decoder.
//
// Note some redundant fields(e.g. block number, txn hash etc) will be assembled later.
func (l *LogForStorage) DecodeRLP(s *rlp.Stream) error {
	_, err := s.List()
	if err != nil {
		return err
	}
	if l.Address, err = s.Addr(); err != nil {
		return fmt.Errorf("read Address: %w", err)
	}
	l.Topics, err = decodeHashList(s)
	if err != nil {
		return err
	}
	if l.Data, err = s.Bytes(); err != nil {
		return fmt.Errorf("read Data: %w", err)
	}
	return s.ListEnd()
}
