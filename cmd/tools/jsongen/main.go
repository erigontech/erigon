// Command jsongen writes a MarshalFastJSONTo for a struct from the struct's own tags: the
// json tag gives each field's name, its position and whether it may be omitted, and the
// ethjson tag gives the form the JSON-RPC spec writes it in. With the encoder generated, the
// tags are the only place the wire format is stated.
//
// usage: jsongen -type RPCLog -dir execution/types -out log_ethjson_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
)

func main() {
	typeName := flag.String("type", "", "struct to generate for")
	dir := flag.String("dir", ".", "package directory holding it")
	out := flag.String("out", "", "file to write, relative to dir")
	flag.Parse()
	if *typeName == "" || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*typeName, *dir, *out); err != nil {
		fmt.Fprintln(os.Stderr, "jsongen:", err)
		os.Exit(1)
	}
}

func run(typeName, dir, out string) error {
	pkg, structs, err := parsePackage(dir)
	if err != nil {
		return err
	}
	target, ok := structs[typeName]
	if !ok {
		return fmt.Errorf("no struct %s in %s", typeName, dir)
	}

	var body bytes.Buffer
	if err := writeFields(&body, target, structs, "x"); err != nil {
		return fmt.Errorf("%s: %w", typeName, err)
	}

	var file bytes.Buffer
	fmt.Fprintf(&file, header, pkg, typeName, body.String())
	formatted, err := format.Source(file.Bytes())
	if err != nil {
		return fmt.Errorf("%s: %w\n%s", typeName, err, file.String())
	}
	return os.WriteFile(filepath.Join(dir, out), formatted, 0o644)
}

const header = `// Code generated by cmd/tools/jsongen. DO NOT EDIT.
// The source of truth is %[2]s's json and ethjson tags.

package %[1]s

import (
	"github.com/erigontech/erigon/rpc/jsonstream"
	"github.com/erigontech/erigon/rpc/jsonstream/ethjson"
)

// MarshalFastJSONTo writes the fields %[2]s declares, in that order.
func (x *%[2]s) MarshalFastJSONTo(s *jsonstream.StackStream) error {
	if x == nil {
		s.WriteNil()
		return nil
	}
	s.WriteObjectStart()
%[3]s	s.WriteObjectEnd()
	return nil
}
`

func parsePackage(dir string) (string, map[string]*ast.StructType, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, 0)
	if err != nil {
		return "", nil, err
	}
	if len(pkgs) != 1 {
		return "", nil, fmt.Errorf("%s holds %d packages, want 1", dir, len(pkgs))
	}
	structs := map[string]*ast.StructType{}
	name := ""
	for pkgName, pkg := range pkgs {
		name = pkgName
		for _, f := range pkg.Files {
			ast.Inspect(f, func(n ast.Node) bool {
				ts, ok := n.(*ast.TypeSpec)
				if !ok {
					return true
				}
				if st, ok := ts.Type.(*ast.StructType); ok {
					structs[ts.Name.Name] = st
				}
				return true
			})
		}
	}
	return name, structs, nil
}

// writeFields emits one statement per field. An embedded struct is flattened, the way
// encoding/json flattens an anonymous field.
func writeFields(w *bytes.Buffer, st *ast.StructType, structs map[string]*ast.StructType, recv string) error {
	for _, f := range st.Fields.List {
		tag := reflect.StructTag("")
		if f.Tag != nil {
			unquoted, err := strconv.Unquote(f.Tag.Value)
			if err != nil {
				return err
			}
			tag = reflect.StructTag(unquoted)
		}
		if len(f.Names) == 0 { // embedded
			// encoding/json nests an anonymous field that carries a name, and flattens it
			// only when it does not, so a tagged one is not ours to inline.
			if _, named := tag.Lookup("json"); named {
				return fmt.Errorf("embedded %s has a json tag, which encoding/json nests", typeString(f.Type))
			}
			embedded, ok := structs[typeString(f.Type)]
			if !ok {
				return fmt.Errorf("embedded %s is not a struct in this package", typeString(f.Type))
			}
			if err := writeFields(w, embedded, structs, recv); err != nil {
				return err
			}
			continue
		}
		for _, id := range f.Names {
			if !id.IsExported() {
				continue
			}
			jsonTag, ok := tag.Lookup("json")
			if !ok {
				return fmt.Errorf("%s: no json tag", id.Name)
			}
			name, opts, _ := strings.Cut(jsonTag, ",")
			if name == "-" {
				continue
			}
			stmt, err := fieldStatement(recv+"."+id.Name, name, tag.Get("ethjson"), typeString(f.Type), strings.Contains(opts, "omitempty"))
			if err != nil {
				return fmt.Errorf("%s: %w", id.Name, err)
			}
			w.WriteString(stmt)
		}
	}
	return nil
}

func typeString(e ast.Expr) string {
	var b bytes.Buffer
	_ = format.Node(&b, token.NewFileSet(), e)
	return b.String()
}

// fieldStatement picks the writer for one field from its declared form and Go type. A field
// its json tag lets omit is wrapped in the presence test encoding/json would apply; without
// omitempty, an absent value is written as null.
func fieldStatement(ref, name, form, goType string, omitempty bool) (string, error) {
	pointer := strings.HasPrefix(goType, "*")
	bare := strings.TrimPrefix(goType, "*")

	var write, present string
	switch form {
	case "":
		return "", fmt.Errorf("no ethjson tag")
	case "bool":
		write = fmt.Sprintf("s.Field(%q).WriteBool(%s)", name, ref)
		present = ref
	case "datalist":
		write = fmt.Sprintf("ethjson.DataList(s, %q, %s)", name, ref)
		present = fmt.Sprintf("len(%s) > 0", ref)
	case "data":
		// Slicing reads the same on an array, a pointer to one and a slice, so the emitted
		// call does not need to know which it has.
		write = fmt.Sprintf("ethjson.Data(s, %q, %s[:])", name, ref)
		if pointer {
			present = ref + " != nil"
		} else {
			present = fmt.Sprintf("len(%s[:]) > 0", ref)
		}
	case "quantity":
		switch {
		case is256(bare) && pointer:
			write = fmt.Sprintf("ethjson.Quantity256(s, %q, (*uint256.Int)(%s))", name, ref)
			present = ref + " != nil"
		case is256(bare):
			write = fmt.Sprintf("ethjson.Quantity256(s, %q, (*uint256.Int)(&%s))", name, ref)
			present = fmt.Sprintf("!(*uint256.Int)(&%s).IsZero()", ref)
		case pointer:
			write = fmt.Sprintf("ethjson.Quantity(s, %q, *%s)", name, ref)
			present = ref + " != nil"
		default:
			write = fmt.Sprintf("ethjson.Quantity(s, %q, %s)", name, ref)
			present = ref + " != 0"
		}
	default:
		return "", fmt.Errorf("unknown ethjson form %q", form)
	}

	switch {
	case omitempty:
		return fmt.Sprintf("\tif %s {\n\t\t%s\n\t}\n", present, write), nil
	case pointer: // absent, and the tag does not allow leaving it out
		return fmt.Sprintf("\tif %s == nil {\n\t\ts.Field(%q).WriteNil()\n\t} else {\n\t\t%s\n\t}\n", ref, name, write), nil
	default:
		return "\t" + write + "\n", nil
	}
}

func is256(goType string) bool {
	switch goType {
	case "uint256.Int", "hexutil.U256":
		return true
	}
	return false
}
