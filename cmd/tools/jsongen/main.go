// Command jsongen writes a MarshalFastJSONTo for a struct from the struct's own tags: the
// json tag gives each field's name, its position and whether it may be omitted, and the
// ethjson tag gives the form the JSON-RPC spec writes it in. With the encoder generated, the
// tags are the only place the wire format is stated.
//
// usage: jsongen -type RPCLog -dir execution/types -out gen_rpclog_json.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"golang.org/x/tools/go/packages"
	"golang.org/x/tools/imports"
)

func main() {
	typeName := flag.String("type", "", "struct to generate for")
	dir := flag.String("dir", ".", "package directory holding it")
	out := flag.String("out", "", "file to write, relative to dir")
	flag.Parse()
	if *typeName == "" || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*typeName, *dir, *out); err != nil {
		fmt.Fprintln(os.Stderr, "jsongen:", err)
		os.Exit(1)
	}
}

func run(typeName, dir, out string) error {
	pkg, err := load(dir)
	if err != nil {
		return err
	}
	obj := pkg.Types.Scope().Lookup(typeName)
	if obj == nil {
		return fmt.Errorf("no %s in %s", typeName, pkg.PkgPath)
	}
	st, ok := obj.Type().Underlying().(*types.Struct)
	if !ok {
		return fmt.Errorf("%s is not a struct", typeName)
	}

	var body bytes.Buffer
	if err := writeFields(&body, st, "x", map[string]struct{}{}); err != nil {
		return fmt.Errorf("%s: %w", typeName, err)
	}

	var file bytes.Buffer
	fmt.Fprintf(&file, header, pkg.Name, typeName, body.String())
	path := filepath.Join(dir, out)
	// imports.Process adds what the body uses and gofmts in one step.
	formatted, err := imports.Process(path, file.Bytes(), nil)
	if err != nil {
		return fmt.Errorf("%s: %w\n%s", typeName, err, file.String())
	}
	return os.WriteFile(path, formatted, 0o644)
}

const header = `// Code generated by cmd/tools/jsongen. DO NOT EDIT.
// The source of truth is %[2]s's json and ethjson tags.

package %[1]s

import (
	"github.com/erigontech/erigon/rpc/jsonstream"
)

// MarshalFastJSONTo writes the fields %[2]s declares, in that order.
func (x *%[2]s) MarshalFastJSONTo(s *jsonstream.StackStream) error {
	if x == nil {
		s.WriteNil()
		return nil
	}
	s.WriteObjectStart()
%[3]s	s.WriteObjectEnd()
	return nil
}
`

func load(dir string) (*packages.Package, error) {
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedTypes | packages.NeedSyntax, Dir: dir}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return nil, err
	}
	if len(pkgs) != 1 {
		return nil, fmt.Errorf("%s holds %d packages, want 1", dir, len(pkgs))
	}
	// Type errors are expected the first time a package is generated for: the method this
	// writes is missing until it exists. The struct's own fields still type-check, and a
	// name that truly is not there fails the lookup below.
	return pkgs[0], nil
}

// writeFields emits one statement per field. An embedded struct is flattened, the way
// encoding/json flattens an anonymous field, and a name written twice is an error rather than
// a silent choice between them.
func writeFields(w *bytes.Buffer, st *types.Struct, recv string, written map[string]struct{}) error {
	for i := range st.NumFields() {
		f, tag := st.Field(i), reflect.StructTag(st.Tag(i))
		if f.Embedded() {
			// encoding/json nests an anonymous field that carries a name, and flattens it
			// only when it does not, so a tagged one is not ours to inline.
			if _, named := tag.Lookup("json"); named {
				return fmt.Errorf("embedded %s has a json tag, which encoding/json nests", f.Name())
			}
			embedded, ok := deref(f.Type()).Underlying().(*types.Struct)
			if !ok {
				return fmt.Errorf("embedded %s is not a struct", f.Name())
			}
			if err := writeFields(w, embedded, recv, written); err != nil {
				return err
			}
			continue
		}
		if !f.Exported() {
			continue
		}
		jsonTag, ok := tag.Lookup("json")
		if !ok {
			return fmt.Errorf("%s: no json tag", f.Name())
		}
		name, opts, _ := strings.Cut(jsonTag, ",")
		if name == "-" {
			continue
		}
		if name == "" {
			name = f.Name() // what encoding/json falls back to
		}
		if _, seen := written[name]; seen {
			return fmt.Errorf("%s: %q is already written; encoding/json would emit it once", f.Name(), name)
		}
		written[name] = struct{}{}

		stmt, err := fieldStatement(recv+"."+f.Name(), name, tag.Get("ethjson"), f.Type(), strings.Contains(opts, "omitempty"))
		if err != nil {
			return fmt.Errorf("%s: %w", f.Name(), err)
		}
		w.WriteString(stmt)
	}
	return nil
}

// fieldStatement picks the writer for one field from its declared form and its type. A field
// its json tag lets omit is wrapped in the presence test encoding/json would apply; without
// omitempty, an absent value is written as null.
func fieldStatement(ref, name, form string, t types.Type, omitempty bool) (string, error) {
	_, pointer := t.Underlying().(*types.Pointer)
	bare := deref(t)

	var write, present string
	switch form {
	case "":
		return "", fmt.Errorf("no ethjson tag")
	case "bool":
		if pointer || !isBasic(bare, types.IsBoolean) {
			return "", fmt.Errorf(`ethjson:"bool" on %s`, t)
		}
		write = fmt.Sprintf("s.Field(%q).WriteBool(%s)", name, ref)
		present = ref
	case "datalist":
		if pointer || !isSliceOfArrays(bare) {
			return "", fmt.Errorf(`ethjson:"datalist" on %s`, t)
		}
		write = fmt.Sprintf("ethjson.DataList(s, %q, %s)", name, ref)
		present = fmt.Sprintf("len(%s) > 0", ref)
	case "data":
		if !isBytes(bare) {
			return "", fmt.Errorf(`ethjson:"data" on %s`, t)
		}
		// Slicing reads the same on an array, a pointer to one and a slice, so the emitted
		// call does not need to know which it has.
		write = fmt.Sprintf("ethjson.Data(s, %q, %s[:])", name, ref)
		if pointer {
			present = ref + " != nil"
		} else {
			present = fmt.Sprintf("len(%s[:]) > 0", ref)
		}
	case "quantity":
		switch {
		case is256(bare) && pointer:
			write = fmt.Sprintf("ethjson.Quantity256(s, %q, (*uint256.Int)(%s))", name, ref)
			present = ref + " != nil"
		case is256(bare):
			write = fmt.Sprintf("ethjson.Quantity256(s, %q, (*uint256.Int)(&%s))", name, ref)
			// uint256.Int is an array of four words, and encoding/json never calls an array
			// empty, so omitempty cannot leave a zero one out.
			omitempty = false
		case !isBasic(bare, types.IsUnsigned):
			return "", fmt.Errorf(`ethjson:"quantity" on %s`, t)
		case pointer:
			write = fmt.Sprintf("ethjson.Quantity(s, %q, *%s)", name, ref)
			present = ref + " != nil"
		default:
			write = fmt.Sprintf("ethjson.Quantity(s, %q, %s)", name, ref)
			present = ref + " != 0"
		}
	default:
		return "", fmt.Errorf("unknown ethjson form %q", form)
	}

	switch {
	case omitempty:
		return fmt.Sprintf("\tif %s {\n\t\t%s\n\t}\n", present, write), nil
	case pointer: // absent, and the tag does not allow leaving it out
		return fmt.Sprintf("\tif %s == nil {\n\t\ts.Field(%q).WriteNil()\n\t} else {\n\t\t%s\n\t}\n", ref, name, write), nil
	default:
		return "\t" + write + "\n", nil
	}
}

func deref(t types.Type) types.Type {
	if p, ok := t.Underlying().(*types.Pointer); ok {
		return p.Elem()
	}
	return t
}

func isBasic(t types.Type, info types.BasicInfo) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Info()&info != 0
}

func isByte(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Kind() == types.Byte
}

// isBytes reports a value the spec writes as data: bytes of their own length, or a fixed-size
// array of them.
func isBytes(t types.Type) bool {
	switch u := t.Underlying().(type) {
	case *types.Slice:
		return isByte(u.Elem())
	case *types.Array:
		return isByte(u.Elem())
	}
	return false
}

func isSliceOfArrays(t types.Type) bool {
	s, ok := t.Underlying().(*types.Slice)
	if !ok {
		return false
	}
	return isBytes(s.Elem())
}

// is256 reports a uint256.Int under any name, so an alias or a named copy such as hexutil.U256
// is recognised by its type rather than by how it is spelled.
func is256(t types.Type) bool {
	a, ok := t.Underlying().(*types.Array)
	if !ok || a.Len() != 4 {
		return false
	}
	b, ok := a.Elem().Underlying().(*types.Basic)
	return ok && b.Kind() == types.Uint64
}
