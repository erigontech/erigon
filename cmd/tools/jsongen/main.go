// Command jsongen writes a MarshalFastJSONTo for a struct from the struct's own tags: the
// json tag gives each field's name, its position and whether it may be omitted, and the
// ethjson tag gives the form the JSON-RPC spec writes it in. With the encoder generated, the
// tags are the only place the wire format is stated.
//
// The ethjson writers are typed exactly, so a form that does not suit the field's type fails
// to compile in the generated file, at that field's line. This checks only what the compiler
// cannot: a form it does not know, a json option it does not implement, and a shape that would
// make it write what encoding/json would not.
//
// It runs in the package directory, as go generate does:
//
//	//go:generate go run github.com/erigontech/erigon/cmd/tools/jsongen -type RPCLog
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/types"
	"os"
	"reflect"
	"strconv"
	"strings"

	"github.com/erigontech/erigon/common/length"

	"golang.org/x/tools/go/packages"
	"golang.org/x/tools/imports"
)

func main() {
	typeName := flag.String("type", "", "struct to generate for")
	out := flag.String("out", "", "file to write; default gen_<type>_json.go")
	computed := flag.String("computed", "", "method to call for fields the struct does not hold")
	flag.Parse()
	if *typeName == "" {
		flag.Usage()
		os.Exit(2)
	}
	if *out == "" {
		*out = "gen_" + strings.ToLower(*typeName) + "_json.go"
	}
	if err := run(*typeName, *out, *computed); err != nil {
		fmt.Fprintln(os.Stderr, "jsongen:", err)
		os.Exit(1)
	}
}

func run(typeName, out, computed string) error {
	pkg, err := load()
	if err != nil {
		return err
	}
	obj := pkg.Types.Scope().Lookup(typeName)
	if obj == nil {
		return fmt.Errorf("no %s in %s", typeName, pkg.PkgPath)
	}
	st, ok := obj.Type().Underlying().(*types.Struct)
	if !ok {
		return fmt.Errorf("%s is not a struct", typeName)
	}

	var body bytes.Buffer
	if err := writeFields(&body, st, "x", map[string]struct{}{}); err != nil {
		return fmt.Errorf("%s: %w", typeName, err)
	}
	// A value the struct does not hold, such as a header's hash, is written by a method the
	// package declares; the generator only calls it, after the declared fields.
	if computed != "" {
		fmt.Fprintf(&body, "\tx.%s(s)\n", computed)
	}

	var file bytes.Buffer
	fmt.Fprintf(&file, header, pkg.Name, typeName, body.String(), method, fieldsMethod)
	// imports.Process drops what the body does not use and gofmts in one step. The header names
	// uint256 rather than leaving it to be resolved, because more than one module supplies that
	// package name and the choice would then follow whoever ran the tool.
	formatted, err := imports.Process(out, file.Bytes(), nil)
	if err != nil {
		return fmt.Errorf("%s: %w\n%s", typeName, err, file.String())
	}
	return os.WriteFile(out, formatted, 0o644)
}

const method = "MarshalFastJSONTo"

// fieldsMethod holds the field statements, so a type that inlines another writes its fields
// without the enclosing object.
const fieldsMethod = "writeJSONFields"

// marker is the first line of every file this writes, and what identifies one.
const marker = "// Code generated by cmd/tools/jsongen."

const header = marker + ` DO NOT EDIT.
// The source of truth is %[2]s's json and ethjson tags.

package %[1]s

import (
	"github.com/holiman/uint256"

	"github.com/erigontech/erigon/rpc/jsonstream"
)

// %[4]s writes the fields %[2]s declares, in that order.
func (x *%[2]s) %[4]s(s *jsonstream.StackStream) error {
	if x == nil {
		s.WriteNil()
		return nil
	}
	s.WriteObjectStart()
	if err := x.%[5]s(s); err != nil {
		return err
	}
	s.WriteObjectEnd()
	return nil
}

// %[5]s writes those fields without the enclosing object, for a type another object inlines.
func (x *%[2]s) %[5]s(s *jsonstream.StackStream) error {
%[3]s	return nil
}
`

// load type-checks the package it runs in, ignoring what its own past output says. A field
// renamed since the last run still has its old name in a generated body, and on a first run the
// method this writes is missing altogether; neither says anything about the tags. Any other
// error does, and stops the run rather than generating from types that will not build.

func load() (*packages.Package, error) {
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedSyntax | packages.NeedTypes |
		packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return nil, err
	}
	if len(pkgs) != 1 {
		return nil, fmt.Errorf("%d packages here, want 1", len(pkgs))
	}
	for _, e := range pkgs[0].Errors {
		if missingWhatThisWrites(e.Msg) {
			continue
		}
		content, err := os.ReadFile(positionFile(e.Pos))
		if err != nil || !bytes.HasPrefix(content, []byte(marker)) {
			return nil, e
		}
	}
	return pkgs[0], nil
}

// missingWhatThisWrites reports the compiler's two wordings for the absence of a method this run
// writes: a call to it, and a value that has to satisfy an interface asking for it. Matching the
// whole phrase keeps any other mention of the name an error.
func missingWhatThisWrites(msg string) bool {
	for _, name := range [...]string{method, fieldsMethod} {
		if strings.Contains(msg, "has no field or method "+name) || strings.Contains(msg, "missing method "+name) {
			return true
		}
	}
	return false
}

// positionFile takes the file out of a packages.Error position. Cutting at the first colon
// would keep only the drive letter of a Windows path, so the line and column come off the right.
func positionFile(pos string) string {
	for range 2 {
		i := strings.LastIndex(pos, ":")
		if i < 0 {
			break
		}
		if _, err := strconv.Atoi(pos[i+1:]); err != nil {
			break
		}
		pos = pos[:i]
	}
	return pos
}

// writeFields emits one statement per field. An embedded struct is flattened, the way
// encoding/json flattens an anonymous field, and a name written twice is an error rather than
// a silent choice between them.
func writeFields(w *bytes.Buffer, st *types.Struct, recv string, written map[string]struct{}) error {
	for i := range st.NumFields() {
		f, tag := st.Field(i), reflect.StructTag(st.Tag(i))
		if f.Embedded() {
			// encoding/json nests an anonymous field that carries a name, and flattens it
			// only when it does not, so a tagged one is not ours to inline.
			if _, named := tag.Lookup("json"); named {
				return fmt.Errorf("embedded %s has a json tag, which encoding/json nests", f.Name())
			}
			// A nil embedded pointer makes encoding/json omit the whole group, which a
			// flattened encoder cannot express, so the generator refuses one.
			if _, ptr := f.Type().Underlying().(*types.Pointer); ptr {
				return fmt.Errorf("embedded %s is a pointer, which may be nil", f.Name())
			}
			embedded, ok := f.Type().Underlying().(*types.Struct)
			if !ok {
				return fmt.Errorf("embedded %s is not a struct", f.Name())
			}
			// Through its own selector, so two promoted names cannot collide.
			if err := writeFields(w, embedded, recv+"."+f.Name(), written); err != nil {
				return err
			}
			continue
		}
		if !f.Exported() {
			continue
		}
		jsonTag, ok := tag.Lookup("json")
		if !ok {
			return fmt.Errorf("%s: no json tag", f.Name())
		}
		name, opts, _ := strings.Cut(jsonTag, ",")
		if jsonTag == "-" { // a lone dash skips the field; `-,` names it "-"
			continue
		}
		omitempty, omitzero := false, false
		for opt := range strings.SplitSeq(opts, ",") {
			switch opt {
			case "":
			case "omitempty":
				omitempty = true
			case "omitzero":
				omitzero = true
			default:
				// string changes what encoding/json writes, so ignoring it would leave the
				// tags and the bytes disagreeing.
				return fmt.Errorf("%s: json option %q is not implemented", f.Name(), opt)
			}
		}
		if name == "" {
			name = f.Name() // what encoding/json falls back to
		}
		if _, seen := written[name]; seen {
			return fmt.Errorf("%s: %q is already written; encoding/json would emit it once", f.Name(), name)
		}
		written[name] = struct{}{}

		stmt, err := fieldStatement(recv+"."+f.Name(), name, tag.Get("ethjson"), f.Type(), omitempty, omitzero)
		if err != nil {
			return fmt.Errorf("%s: %w", f.Name(), err)
		}
		w.WriteString(stmt)
	}
	return nil
}

// fieldStatement picks the writer for one field from its declared form. A field its json tag
// lets omit is wrapped in the presence test encoding/json would apply; without omitempty, an
// absent value is written as null.
func fieldStatement(ref, name, form string, t types.Type, omitempty, omitzero bool) (string, error) {
	_, pointer := t.Underlying().(*types.Pointer)
	_, iface := t.Underlying().(*types.Interface)

	var write, present string
	switch form {
	case "":
		return "", fmt.Errorf("no ethjson tag")
	case "bool":
		write = fmt.Sprintf("s.Field(%q).WriteBool(%s)", name, ref)
		present = ref
	case "objects":
		write = fmt.Sprintf("s.Field(%q)\nif err := %s.%s(s); err != nil {\nreturn err\n}", name, ref, method)
		switch {
		case pointer || iface:
			present = ref + " != nil"
		case isLenable(t):
			present = fmt.Sprintf("len(%s) > 0", ref)
		case omitempty:
			// A struct writes itself and cannot be compared with nil, so nothing here can
			// say whether encoding/json would have left it out.
			return "", fmt.Errorf(`ethjson:%q cannot be omitempty on %s`, form, t)
		}
	case "datalist":
		// Both writers grow the buffer once; DataList takes only a hash-sized element, which
		// is the whole of what decides between them.
		writer := "Datas"
		if slice, ok := t.Underlying().(*types.Slice); ok {
			if a, fixed := slice.Elem().Underlying().(*types.Array); fixed && a.Len() == length.Hash {
				writer = "DataList"
			}
		}
		write = fmt.Sprintf("ethjson.%s(s, %q, %s)", writer, name, ref)
		present = fmt.Sprintf("len(%s) > 0", ref)
	case "data":
		// Slicing reads the same on an array and on a pointer to one, but a pointer to a slice
		// has to be dereferenced first.
		sliced := ref + "[:]"
		if _, slice := deref(t).Underlying().(*types.Slice); slice && pointer {
			sliced = "(*" + ref + ")[:]"
		}
		write = fmt.Sprintf("ethjson.Data(s, %q, %s)", name, sliced)
		if pointer {
			present = ref + " != nil"
		} else {
			present = fmt.Sprintf("len(%s) > 0", ref) // an array is never empty, so omitempty cannot fire
		}
	case "quantity":
		bare := deref(t)
		switch {
		case is256(bare) && pointer:
			write = fmt.Sprintf("ethjson.Quantity256(s, %q, (*uint256.Int)(%s))", name, ref)
			present = ref + " != nil"
		case is256(bare):
			write = fmt.Sprintf("ethjson.Quantity256(s, %q, (*uint256.Int)(&%s))", name, ref)
			// uint256.Int is an array of four words, and encoding/json never calls an array
			// empty, so omitempty cannot leave a zero one out.
			omitempty = false
		case pointer:
			write = fmt.Sprintf("ethjson.Quantity(s, %q, *%s)", name, ref)
			present = ref + " != nil"
		default:
			write = fmt.Sprintf("ethjson.Quantity(s, %q, %s)", name, ref)
			present = ref + " != 0"
		}
	default:
		return "", fmt.Errorf("unknown ethjson form %q", form)
	}

	switch {
	case omitzero:
		// encoding/json asks an IsZero method first, and a nil test is only its answer
		// for a type without one.
		if !(pointer || iface || isLenable(t)) || types.NewMethodSet(t).Lookup(nil, "IsZero") != nil {
			return "", fmt.Errorf("omitzero is implemented for a nil-able type without IsZero only, not %s", t)
		}
		return fmt.Sprintf("\tif %s != nil {\n\t\t%s\n\t}\n", ref, write), nil
	case omitempty:
		return fmt.Sprintf("\tif %s {\n\t\t%s\n\t}\n", present, write), nil
	case pointer || iface: // absent, and the tag does not allow leaving it out
		return fmt.Sprintf("\tif %s == nil {\n\t\ts.Field(%q).WriteNil()\n\t} else {\n\t\t%s\n\t}\n", ref, name, write), nil
	default:
		return "\t" + write + "\n", nil
	}
}

// isLenable reports a type whose emptiness len reports, which is how encoding/json decides
// omitempty for it.
func isLenable(t types.Type) bool {
	switch t.Underlying().(type) {
	case *types.Slice, *types.Map:
		return true
	}
	return false
}

func deref(t types.Type) types.Type {
	if p, ok := t.Underlying().(*types.Pointer); ok {
		return p.Elem()
	}
	return t
}

// the256 lists the types written as a 256-bit quantity. Matching the underlying [4]uint64
// alone would accept any four-word array, which the emitted conversion would misread.
var the256 = map[string]bool{
	"github.com/holiman/uint256.Int":                   true,
	"github.com/erigontech/erigon/common/hexutil.U256": true,
}

// is256 reports one of those, under an alias or not, since an alias denotes the same named type.
func is256(t types.Type) bool {
	named, ok := types.Unalias(t).(*types.Named)
	if !ok || named.Obj().Pkg() == nil {
		return false
	}
	return the256[named.Obj().Pkg().Path()+"."+named.Obj().Name()]
}
