// Command jsongen writes a MarshalFastJSONTo for a struct from the struct's own tags: the
// json tag gives each field's name, its position and whether it may be omitted, and the
// ethjson tag gives the form the JSON-RPC spec writes it in. With the encoder generated, the
// tags are the only place the wire format is stated.
//
// usage: jsongen -type RPCLog -dir execution/types -out gen_rpclog_json.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/erigontech/erigon/common/length"

	"golang.org/x/tools/go/packages"
	"golang.org/x/tools/imports"
)

func main() {
	typeName := flag.String("type", "", "struct to generate for")
	dir := flag.String("dir", ".", "package directory holding it")
	out := flag.String("out", "", "file to write, relative to dir unless absolute")
	computed := flag.String("computed", "", "method to call for fields the struct does not hold")
	flag.Parse()
	if *typeName == "" || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*typeName, *dir, *out, *computed); err != nil {
		fmt.Fprintln(os.Stderr, "jsongen:", err)
		os.Exit(1)
	}
}

func run(typeName, dir, out, computed string) error {
	path := out
	if !filepath.IsAbs(out) {
		path = filepath.Join(dir, out)
	}
	pkg, err := load(dir, path)
	if err != nil {
		return err
	}
	obj := pkg.Types.Scope().Lookup(typeName)
	if obj == nil {
		return fmt.Errorf("no %s in %s", typeName, pkg.PkgPath)
	}
	st, ok := obj.Type().Underlying().(*types.Struct)
	if !ok {
		return fmt.Errorf("%s is not a struct", typeName)
	}

	var body bytes.Buffer
	if err := writeFields(pkg.Types, &body, st, "x", map[string]struct{}{}); err != nil {
		return fmt.Errorf("%s: %w", typeName, err)
	}
	// A value the struct does not hold, such as a header's hash, is written by a method the
	// package declares; the generator only calls it, after the declared fields.
	if computed != "" {
		if !declares(pkg.Types, obj.Type(), computed, 0) {
			return fmt.Errorf("%s has no %s(*jsonstream.StackStream)", typeName, computed)
		}
		fmt.Fprintf(&body, "\tx.%s(s)\n", computed)
	}

	var file bytes.Buffer
	fmt.Fprintf(&file, header, pkg.Name, typeName, body.String(), method)
	// imports.Process adds what the body uses and gofmts in one step.
	formatted, err := imports.Process(path, file.Bytes(), nil)
	if err != nil {
		return fmt.Errorf("%s: %w\n%s", typeName, err, file.String())
	}
	return os.WriteFile(path, formatted, 0o644)
}

const method = "MarshalFastJSONTo"

// marker is the first line of every file this writes, and what identifies one to blank.
const marker = "// Code generated by cmd/tools/jsongen."

const header = marker + ` DO NOT EDIT.
// The source of truth is %[2]s's json and ethjson tags.

package %[1]s

import (
	"github.com/erigontech/erigon/rpc/jsonstream"
)

// %[4]s writes the fields %[2]s declares, in that order.
func (x *%[2]s) %[4]s(s *jsonstream.StackStream) error {
	if x == nil {
		s.WriteNil()
		return nil
	}
	s.WriteObjectStart()
%[3]s	s.WriteObjectEnd()
	return nil
}
`

// load type-checks the package with every file this tool generates replaced by a bare package
// clause. A field renamed since the last run still has its old name in each of them, so
// leaving a sibling in place would fail the run that is about to rewrite it.
func load(dir, out string) (*packages.Package, error) {
	name, err := packageName(dir)
	if err != nil {
		return nil, err
	}
	overlay, err := blankGenerated(dir, out, name)
	if err != nil {
		return nil, err
	}
	cfg := &packages.Config{
		Mode:    packages.NeedName | packages.NeedTypes | packages.NeedSyntax,
		Dir:     dir,
		Overlay: overlay,
	}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return nil, err
	}
	if len(pkgs) != 1 {
		return nil, fmt.Errorf("%s holds %d packages, want 1", dir, len(pkgs))
	}
	// Blanking the output leaves the package without the method this writes, which every
	// caller of it then reports. Only that error is tolerated, so a typo elsewhere cannot
	// pass for it and leave the tags being read different from the ones that will build.
	for _, e := range pkgs[0].Errors {
		if !strings.Contains(e.Msg, method) {
			return nil, e
		}
	}
	return pkgs[0], nil
}

// blankGenerated maps the file being written, and every sibling this tool wrote, to a bare
// package clause.
func blankGenerated(dir, out, name string) (map[string][]byte, error) {
	blank := []byte("package " + name + "\n")
	abs, err := filepath.Abs(out)
	if err != nil {
		return nil, err
	}
	overlay := map[string][]byte{abs: blank}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		path := filepath.Join(dir, e.Name())
		content, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		if !bytes.HasPrefix(content, []byte(marker)) {
			continue
		}
		abs, err := filepath.Abs(path)
		if err != nil {
			return nil, err
		}
		overlay[abs] = blank
	}
	return overlay, nil
}

// packageName reads the package clause without type-checking, so a package that does not
// compile still yields one.
func packageName(dir string) (string, error) {
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedName, Dir: dir}, ".")
	if err != nil {
		return "", err
	}
	if len(pkgs) != 1 || pkgs[0].Name == "" {
		return "", fmt.Errorf("%s has no single package name", dir)
	}
	return pkgs[0].Name, nil
}

// writeFields emits one statement per field. An embedded struct is flattened, the way
// encoding/json flattens an anonymous field, and a name written twice is an error rather than
// a silent choice between them.
func writeFields(pkg *types.Package, w *bytes.Buffer, st *types.Struct, recv string, written map[string]struct{}) error {
	for i := range st.NumFields() {
		f, tag := st.Field(i), reflect.StructTag(st.Tag(i))
		if f.Embedded() {
			// encoding/json nests an anonymous field that carries a name, and flattens it
			// only when it does not, so a tagged one is not ours to inline.
			if _, named := tag.Lookup("json"); named {
				return fmt.Errorf("embedded %s has a json tag, which encoding/json nests", f.Name())
			}
			// A nil embedded pointer makes encoding/json omit the whole group, which a
			// flattened encoder cannot express, so the generator refuses one.
			if _, ptr := f.Type().Underlying().(*types.Pointer); ptr {
				return fmt.Errorf("embedded %s is a pointer, which may be nil", f.Name())
			}
			embedded, ok := f.Type().Underlying().(*types.Struct)
			if !ok {
				return fmt.Errorf("embedded %s is not a struct", f.Name())
			}
			if err := writeFields(pkg, w, embedded, recv+"."+f.Name(), written); err != nil {
				return err
			}
			continue
		}
		if !f.Exported() {
			continue
		}
		jsonTag, ok := tag.Lookup("json")
		if !ok {
			return fmt.Errorf("%s: no json tag", f.Name())
		}
		name, opts, _ := strings.Cut(jsonTag, ",")
		if name == "-" {
			continue
		}
		omitempty := false
		for _, opt := range strings.Split(opts, ",") {
			switch opt {
			case "":
			case "omitempty":
				omitempty = true
			default:
				// omitzero and string change what encoding/json writes, so ignoring one
				// would leave the tags and the bytes disagreeing.
				return fmt.Errorf("%s: json option %q is not implemented", f.Name(), opt)
			}
		}
		if name == "" {
			name = f.Name() // what encoding/json falls back to
		}
		if _, seen := written[name]; seen {
			return fmt.Errorf("%s: %q is already written; encoding/json would emit it once", f.Name(), name)
		}
		written[name] = struct{}{}

		stmt, err := fieldStatement(pkg, recv+"."+f.Name(), name, tag.Get("ethjson"), f.Type(), omitempty)
		if err != nil {
			return fmt.Errorf("%s: %w", f.Name(), err)
		}
		w.WriteString(stmt)
	}
	return nil
}

// fieldStatement picks the writer for one field from its declared form and its type. A field
// its json tag lets omit is wrapped in the presence test encoding/json would apply; without
// omitempty, an absent value is written as null.
func fieldStatement(pkg *types.Package, ref, name, form string, t types.Type, omitempty bool) (string, error) {
	_, pointer := t.Underlying().(*types.Pointer)
	_, iface := t.Underlying().(*types.Interface)
	bare := deref(t)

	var write, present string
	switch form {
	case "":
		return "", fmt.Errorf("no ethjson tag")
	case "bool":
		if pointer || !isBool(bare) {
			return "", fmt.Errorf(`ethjson:"bool" on %s`, t)
		}
		write = fmt.Sprintf("s.Field(%q).WriteBool(%s)", name, ref)
		present = ref
	case "objects":
		if !declares(pkg, bare, method, 1) {
			return "", fmt.Errorf(`ethjson:%q on %s, which has no %s`, form, t, method)
		}
		if omitempty {
			// Emptiness is the marshaller's own business, and a struct-backed one cannot
			// even be compared with nil.
			return "", fmt.Errorf(`ethjson:%q cannot be omitempty`, form)
		}
		write = fmt.Sprintf("s.Field(%q)\nif err := %s.%s(s); err != nil {\nreturn err\n}", name, ref, method)
		present = ref + " != nil"
	case "datalist":
		if pointer || !isHashSlice(bare) {
			return "", fmt.Errorf(`ethjson:"datalist" on %s, which ethjson.DataList does not take`, t)
		}
		write = fmt.Sprintf("ethjson.DataList(s, %q, %s)", name, ref)
		present = fmt.Sprintf("len(%s) > 0", ref)
	case "data":
		if !isBytes(bare) {
			return "", fmt.Errorf(`ethjson:"data" on %s`, t)
		}
		if _, slice := bare.Underlying().(*types.Slice); slice && pointer {
			return "", fmt.Errorf(`ethjson:"data" on %s: a pointer to a slice cannot be sliced`, t)
		}
		// Slicing reads the same on an array, a pointer to one and a slice, so the emitted
		// call does not need to know which it has.
		write = fmt.Sprintf("ethjson.Data(s, %q, %s[:])", name, ref)
		if pointer {
			present = ref + " != nil"
		} else {
			present = fmt.Sprintf("len(%s) > 0", ref) // an array is never empty, so omitempty cannot fire
		}
	case "quantity":
		switch {
		case is256(bare) && pointer:
			write = fmt.Sprintf("ethjson.Quantity256(s, %q, (*uint256.Int)(%s))", name, ref)
			present = ref + " != nil"
		case is256(bare):
			write = fmt.Sprintf("ethjson.Quantity256(s, %q, (*uint256.Int)(&%s))", name, ref)
			// uint256.Int is an array of four words, and encoding/json never calls an array
			// empty, so omitempty cannot leave a zero one out.
			omitempty = false
		case !isQuantity(bare):
			return "", fmt.Errorf(`ethjson:"quantity" on %s, which ethjson.Quantity does not take`, t)
		case pointer:
			write = fmt.Sprintf("ethjson.Quantity(s, %q, *%s)", name, ref)
			present = ref + " != nil"
		default:
			write = fmt.Sprintf("ethjson.Quantity(s, %q, %s)", name, ref)
			present = ref + " != 0"
		}
	default:
		return "", fmt.Errorf("unknown ethjson form %q", form)
	}

	switch {
	case omitempty:
		return fmt.Sprintf("\tif %s {\n\t\t%s\n\t}\n", present, write), nil
	case pointer || iface: // absent, and the tag does not allow leaving it out
		return fmt.Sprintf("\tif %s == nil {\n\t\ts.Field(%q).WriteNil()\n\t} else {\n\t\t%s\n\t}\n", ref, name, write), nil
	default:
		return "\t" + write + "\n", nil
	}
}

func deref(t types.Type) types.Type {
	if p, ok := t.Underlying().(*types.Pointer); ok {
		return p.Elem()
	}
	return t
}

func isBool(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Info()&types.IsBoolean != 0
}

func isByte(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Kind() == types.Byte
}

// isBytes reports a value the spec writes as data: bytes of their own length, or a fixed-size
// array of them.
func isBytes(t types.Type) bool {
	switch u := t.Underlying().(type) {
	case *types.Slice:
		return isByte(u.Elem())
	case *types.Array:
		return isByte(u.Elem())
	}
	return false
}

// isHashSlice reports what ethjson.DataList takes: a slice of hash-sized byte arrays.
func isHashSlice(t types.Type) bool {
	s, ok := t.Underlying().(*types.Slice)
	if !ok {
		return false
	}
	a, ok := s.Elem().Underlying().(*types.Array)
	return ok && a.Len() == length.Hash && isByte(a.Elem())
}

// isQuantity reports what ethjson.Quantity takes. A narrower unsigned type is rejected rather
// than widened, so the emitted call always compiles.
func isQuantity(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && (b.Kind() == types.Uint || b.Kind() == types.Uint64)
}

// the256 lists the types the generated code converts to *uint256.Int. Matching the underlying
// [4]uint64 alone would accept any four-word array, which that conversion would misread.
var the256 = map[string]bool{
	"github.com/holiman/uint256.Int":                   true,
	"github.com/erigontech/erigon/common/hexutil.U256": true,
}

// is256 reports one of those, under an alias or not, since an alias denotes the same named type.
func is256(t types.Type) bool {
	named, ok := types.Unalias(t).(*types.Named)
	if !ok || named.Obj().Pkg() == nil {
		return false
	}
	return the256[named.Obj().Pkg().Path()+"."+named.Obj().Name()]
}

// declares reports a method the generated code may call: one taking a stream and returning
// results many. LookupFieldOrMethod answers for a named type and for an interface alike, and
// pkg is what finds an unexported one.
func declares(pkg *types.Package, t types.Type, name string, results int) bool {
	obj, _, _ := types.LookupFieldOrMethod(t, true, pkg, name)
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}
	sig := fn.Signature()
	if sig.Params().Len() != 1 || sig.Results().Len() != results || sig.Variadic() {
		return false
	}
	if results == 1 && sig.Results().At(0).Type().String() != "error" {
		return false
	}
	return sig.Params().At(0).Type().String() == streamType
}

const streamType = "*github.com/erigontech/erigon/rpc/jsonstream.StackStream"
